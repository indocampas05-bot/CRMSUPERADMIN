import React, { useState } from 'react';
import {
  ROLES,
  emptyTelecaller,
  DEFAULT_PERMISSIONS
} from './telecallersData';

const AddTelecaller = ({
  telecallers,
  editing,
  onSave,
  onCancel
}) => {

  const [form, setForm] = useState(() => {
    if (editing) {
      return {
        ...editing,
        fullName: editing.fullName || editing.name || '',
        name: editing.fullName || editing.name || '',
        permissions: editing.permissions || { ...DEFAULT_PERMISSIONS }
      };
    }

    return {
      ...emptyTelecaller,
      id: '',
      employeeId: '',
      fullName: '',
      name: '',
      mobile: '',
      email: '',
      username: '',
      password: '',
      role: 'Telecaller',
      status: 'Active',
      joiningDate: '',
      target: 100,
      districts: [],
      categories: [],
      permissions: { ...DEFAULT_PERMISSIONS }
    };
  });

  const updateField = (field, value) => {
    setForm(prev => ({
      ...prev,
      [field]: value
    }));
  };

  const handleSubmit = (e) => {
    e.preventDefault();

    if (
      !form.fullName?.trim() ||
      !form.mobile?.trim() ||
      !form.username?.trim()
    ) {
      alert('Full Name, Mobile and Username are required.');
      return;
    }

    const submitData = {
      ...form,
      fullName: form.fullName.trim(),
      name: form.fullName.trim(),
      mobile: form.mobile.trim(),
      username: form.username.trim(),
      email: form.email || '',
      password: form.password || '',
      role: form.role || 'Telecaller',
      status: form.status || 'Active',
      target: Number(form.target ?? 100),
      permissions: form.permissions || { ...DEFAULT_PERMISSIONS },
      districts: [],
      categories: []
    };

    if (!editing) {
      delete submitData.id;
      delete submitData.employeeId;
    }

    onSave(submitData);
  };

  return (
    <div className="tca-container">

      {/* Header */}
      <div className="tca-header">
        <div className="tca-heading-content">
          <div className="tca-heading-icon">
            <svg
              width="22"
              height="22"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="1.8"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <path d="M16 21v-2a4 4 0 0 0-4-4H6a4 4 0 0 0-4 4v2" />
              <circle cx="9" cy="7" r="4" />
              <line x1="19" y1="8" x2="19" y2="14" />
              <line x1="22" y1="11" x2="16" y2="11" />
            </svg>
          </div>

          <div>
            <h2>
              {editing ? 'Edit Telecaller' : 'Add New Telecaller'}
            </h2>
            <p>
              {editing
                ? 'Update employee information and account details.'
                : 'Create a new telecaller account and manage employee details.'}
            </p>
          </div>
        </div>

        <button
          type="button"
          className="tca-close-btn"
          onClick={onCancel}
          aria-label="Close"
        >
          ×
        </button>
      </div>

      {/* Form */}
      <form className="tca-form" onSubmit={handleSubmit}>

        <div className="tca-section-heading">
          <span>Employee Information</span>
          <span className="tca-required-text">
            * Required fields
          </span>
        </div>

        <div className="tca-grid">

          {/* Employee ID */}
          <div className="tca-field">
            <label>Employee ID</label>

            <input
              type="text"
              value={
                form.id ||
                form.employeeId ||
                'Auto-generated'
              }
              disabled
              className="tca-readonly"
            />

            {!editing && (
              <small className="tca-helper">
                Automatically generated by the system
              </small>
            )}
          </div>

          {/* Status */}
          <div className="tca-field">
            <label>Status</label>

            <select
              value={form.status || 'Active'}
              onChange={e => updateField('status', e.target.value)}
            >
              <option value="Active">Active</option>
              <option value="Inactive">Inactive</option>
            </select>
          </div>

          {/* Full Name */}
          <div className="tca-field">
            <label>
              Full Name <span>*</span>
            </label>

            <input
              type="text"
              placeholder="Enter full name"
              value={form.fullName || ''}
              onChange={e => {
                setForm(prev => ({
                  ...prev,
                  fullName: e.target.value,
                  name: e.target.value
                }));
              }}
              required
            />
          </div>

          {/* Mobile */}
          <div className="tca-field">
            <label>
              Mobile Number <span>*</span>
            </label>

            <input
              type="tel"
              placeholder="Enter mobile number"
              value={form.mobile || ''}
              onChange={e => updateField('mobile', e.target.value)}
              required
            />
          </div>

          {/* Email */}
          <div className="tca-field">
            <label>Email Address</label>

            <input
              type="email"
              placeholder="Enter email address"
              value={form.email || ''}
              onChange={e => updateField('email', e.target.value)}
            />
          </div>

          {/* Username */}
          <div className="tca-field">
            <label>
              Username <span>*</span>
            </label>

            <input
              type="text"
              placeholder="Create username"
              value={form.username || ''}
              onChange={e => updateField('username', e.target.value)}
              required
            />
          </div>

          {/* Password */}
          <div className="tca-field">
            <label>Password</label>

            <input
              type="password"
              placeholder={
                editing
                  ? 'Leave blank to keep current password'
                  : 'Leave blank to auto-generate'
              }
              value={form.password || ''}
              onChange={e => updateField('password', e.target.value)}
            />

            {!editing && (
              <small className="tca-helper">
                Leave blank to generate a secure password automatically
              </small>
            )}
          </div>

          {/* Role */}
          <div className="tca-field">
            <label>Role</label>

            <select
              value={form.role || 'Telecaller'}
              onChange={e => updateField('role', e.target.value)}
            >
              {ROLES.map(role => (
                <option key={role} value={role}>
                  {role}
                </option>
              ))}
            </select>
          </div>

          {/* Joining Date */}
          <div className="tca-field">
            <label>Joining Date</label>

            <input
              type="text"
              placeholder="e.g. 12 Jan 2026"
              value={form.joiningDate || ''}
              onChange={e => updateField('joiningDate', e.target.value)}
            />
          </div>

          {/* Monthly Target */}
          <div className="tca-field">
            <label>Monthly Target (Leads)</label>

            <input
              type="number"
              min="0"
              placeholder="Enter monthly target"
              value={form.target ?? 100}
              onChange={e => updateField('target', e.target.value)}
            />
          </div>

        </div>

        {/* Information Note */}
        <div className="tca-note">
          <div className="tca-note-icon">i</div>

          <div>
            <strong>Assignment Information</strong>
            <p>
              Districts and Categories can be assigned from the
              <strong> Leads </strong>
              section after creating the telecaller.
            </p>
          </div>
        </div>

        {/* Footer */}
        <div className="tca-footer">

          <button
            type="button"
            className="tca-cancel-btn"
            onClick={onCancel}
          >
            Cancel
          </button>

          <button
            type="submit"
            className="tca-submit-btn"
          >
            {editing ? 'Save Changes' : 'Create Telecaller'}
          </button>

        </div>

      </form>
    </div>
  );
};

export default AddTelecaller;
