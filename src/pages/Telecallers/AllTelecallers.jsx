// src/pages/Telecallers/AddTelecaller.jsx
import React, { useState, useEffect } from 'react';
import { CATEGORIES, ROLES, emptyTelecaller, DEFAULT_PERMISSIONS } from './telecallersData';
import { superAdminService } from '../../services/superAdminService';

// Fallback static districts in case API fails
const FALLBACK_DISTRICTS = [
  'Chennai', 'Chengalpattu', 'Kanchipuram', 'Coimbatore', 'Madurai', 
  'Trichy', 'Salem', 'Cuddalore', 'Pondicherry', 'Villupuram', 'Thindivanam'
];

const AddTelecaller = ({ telecallers, editing, onSave, onCancel }) => {
  const [districts, setDistricts] = useState([]);
  const [loadingDistricts, setLoadingDistricts] = useState(true);
  const [error, setError] = useState(null);
  
  const [form, setForm] = useState(() => {
    if (editing) {
      // For editing, use existing data
      const permissions = editing.permissions || { ...DEFAULT_PERMISSIONS };
      return { 
        ...editing, 
        permissions,
        name: editing.fullName || editing.name || '',
        fullName: editing.fullName || editing.name || '',
      };
    } else {
      // For new telecaller, DON'T set an ID - let backend generate it
      return { 
        ...emptyTelecaller, 
        id: '', // Remove the ID
        employeeId: '', // Remove employee ID
        permissions: { ...DEFAULT_PERMISSIONS }
      };
    }
  });

  // Fetch districts from API
  useEffect(() => {
    const fetchDistricts = async () => {
      try {
        setLoadingDistricts(true);
        setError(null);
        
        const data = await superAdminService.getDistricts();
        
        if (data && Array.isArray(data) && data.length > 0) {
          const districtNames = data.map(d => d.name || d);
          setDistricts(districtNames);
        } else {
          setDistricts(FALLBACK_DISTRICTS);
        }
      } catch (error) {
        console.error('Failed to fetch districts:', error);
        setDistricts(FALLBACK_DISTRICTS);
        setError('Could not load districts from server. Using default list.');
      } finally {
        setLoadingDistricts(false);
      }
    };

    fetchDistricts();
  }, []);

  const toggleMulti = (field, value) => {
    setForm((f) => {
      const has = f[field].includes(value);
      return { ...f, [field]: has ? f[field].filter((v) => v !== value) : [...f[field], value] };
    });
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    
    // Validate
    if (!form.fullName || !form.mobile || !form.username) {
      alert('Name, Mobile and Username are required.');
      return;
    }
    
    // Prepare data for submission
    const submitData = {
      ...form,
      fullName: form.fullName || form.name,
      name: form.fullName || form.name,
      permissions: form.permissions || { ...DEFAULT_PERMISSIONS },
    };
    
    // Remove id and employeeId for new telecallers (let backend generate)
    if (!editing) {
      delete submitData.id;
      delete submitData.employeeId;
    }
    
    onSave(submitData);
  };

  return (
    <div className="tc-section">
      <div className="tc-form-card">
        <h3 className="tc-form-title">
          {editing ? `Edit Telecaller — ${editing.fullName || editing.name}` : 'Add New Telecaller'}
        </h3>
        
        {error && (
          <div style={{ 
            padding: '10px', 
            background: '#fef3c7', 
            border: '1px solid #f59e0b',
            borderRadius: '8px',
            marginBottom: '16px',
            color: '#92400e',
            fontSize: '13px'
          }}>
            ⚠️ {error}
          </div>
        )}
        
        <form onSubmit={handleSubmit} className="modal-form">
          <div className="form-grid">
            <div className="form-field">
              <label>Employee ID</label>
              <input 
                value={form.id || form.employeeId || 'Auto-generated'} 
                disabled 
                style={{ color: '#6b7280' }}
              />
              {!editing && (
                <small style={{ color: '#6b7280', fontSize: '11px' }}>
                  💡 Will be auto-generated by the system
                </small>
              )}
            </div>
            <div className="form-field">
              <label>Status</label>
              <select 
                value={form.status || 'Active'} 
                onChange={(e) => setForm({ ...form, status: e.target.value })}
              >
                <option>Active</option>
                <option>Inactive</option>
              </select>
            </div>
            <div className="form-field">
              <label>Full Name *</label>
              <input 
                value={form.fullName || form.name || ''} 
                onChange={(e) => setForm({ ...form, fullName: e.target.value, name: e.target.value })} 
                required 
              />
            </div>
            <div className="form-field">
              <label>Mobile Number *</label>
              <input 
                value={form.mobile || ''} 
                onChange={(e) => setForm({ ...form, mobile: e.target.value })} 
                required 
              />
            </div>
            <div className="form-field">
              <label>Email</label>
              <input 
                type="email" 
                value={form.email || ''} 
                onChange={(e) => setForm({ ...form, email: e.target.value })} 
              />
            </div>
            <div className="form-field">
              <label>Username *</label>
              <input 
                value={form.username || ''} 
                onChange={(e) => setForm({ ...form, username: e.target.value })} 
                required 
              />
            </div>
            <div className="form-field">
              <label>Password</label>
              <input 
                type="text"
                value={form.password || ''} 
                onChange={(e) => setForm({ ...form, password: e.target.value })} 
                placeholder={editing ? "Leave blank to keep current" : "Leave blank to auto-generate"}
              />
              {!editing && (
                <small style={{ color: '#6b7280', fontSize: '11px' }}>
                  💡 Leave blank to auto-generate a secure password
                </small>
              )}
            </div>
            <div className="form-field">
              <label>Role</label>
              <select 
                value={form.role || 'Telecaller'} 
                onChange={(e) => setForm({ ...form, role: e.target.value })}
              >
                {ROLES.map((r) => <option key={r}>{r}</option>)}
              </select>
            </div>
            <div className="form-field">
              <label>Joining Date</label>
              <input 
                placeholder="e.g. 12 Jan 2026" 
                value={form.joiningDate || ''} 
                onChange={(e) => setForm({ ...form, joiningDate: e.target.value })} 
              />
            </div>
            <div className="form-field">
              <label>Monthly Target (leads)</label>
              <input 
                type="number" 
                value={form.target || 100} 
                onChange={(e) => setForm({ ...form, target: Number(e.target.value) })} 
              />
            </div>
          </div>

          <div className="form-field">
            <label>Assign Districts</label>
            {loadingDistricts ? (
              <div style={{ padding: '10px', color: '#6b7280' }}>
                <span>⏳</span> Loading districts...
              </div>
            ) : districts.length === 0 ? (
              <div style={{ padding: '10px', color: '#b45309', background: '#fef3c7', borderRadius: '6px' }}>
                ⚠️ No districts found. Please create districts first in the Leads section.
              </div>
            ) : (
              <div className="checkbox-grid">
                {districts.map((d) => (
                  <label key={d} className="checkbox-pill">
                    <input 
                      type="checkbox" 
                      checked={(form.districts || []).includes(d)} 
                      onChange={() => toggleMulti('districts', d)} 
                    />
                    {d}
                  </label>
                ))}
              </div>
            )}
          </div>

          <div className="form-field">
            <label>Assign Categories</label>
            <div className="checkbox-grid">
              {CATEGORIES.map((c) => (
                <label key={c} className="checkbox-pill">
                  <input 
                    type="checkbox" 
                    checked={(form.categories || []).includes(c)} 
                    onChange={() => toggleMulti('categories', c)} 
                  />
                  {c}
                </label>
              ))}
            </div>
          </div>

          <div className="modal-footer">
            <button type="button" className="secondary-btn" onClick={onCancel}>
              Cancel
            </button>
            <button type="submit" className="primary-btn">
              {editing ? 'Save Changes' : 'Create Telecaller'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};

export default AddTelecaller;